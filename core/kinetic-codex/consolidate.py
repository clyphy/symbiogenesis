#!/usr/bin/env python3
"""Merge ~/NAA and ~/core/NAA into the canonical tree, then MOVE (not delete) them to ~/Backups.
Never overwrites. Aborts before any move if a file is unaccounted for."""
import os, shutil, hashlib, time, sys

H = "/home/wayfinder/"
CANON = H + "projects/symbiogenesis/core/NAA"
TREES = {"home-NAA": H + "NAA", "core-NAA": H + "core/NAA"}
BACKUP = H + "Backups/naa-retired-2026-10-04"
MERGED = CANON + "/_merged_from"
SKIP_DIRS = {"node_modules", ".git", "venv", "__pycache__", ".cache"}
TRANSIENT = ("-shm", "-wal", "-journal")

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()

def files(root):
    out = {}
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in fn:
            p = os.path.join(dp, f)
            if os.path.islink(p):
                continue
            out[os.path.relpath(p, root)] = p
    return out

canon_files = files(CANON)
canon_hash = {}
for rel, p in canon_files.items():
    if "/_merged_from/" in p:
        continue
    canon_hash.setdefault(sha(p), rel)

log = ["# Merge log 2026-10-04 (generated by consolidate.py)", ""]
unaccounted = []
copied_new = copied_ver = skipped = 0

for slug, tree in TREES.items():
    if not os.path.isdir(tree) or os.path.islink(tree):
        log.append("## %s: not a real directory, skipped" % tree)
        continue
    log.append("## %s -> %s" % (tree.replace(H, "~/"), slug))
    for rel, p in sorted(files(tree).items()):
        h = sha(p)
        size = os.path.getsize(p)
        dest = os.path.join(CANON, rel)
        if rel.endswith(TRANSIENT):
            skipped += 1
            log.append("- skip transient: %s" % rel)
        elif rel in canon_files and sha(canon_files[rel]) == h:
            pass  # identical
        elif h in canon_hash:
            pass  # same content already in canonical (other path)
        elif rel not in canon_files:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            if not os.path.exists(dest):
                shutil.copy2(p, dest)
                copied_new += 1
                log.append("- NEW into canonical: %s (%d B, %s)" % (rel, size, h[:10]))
        else:
            # same relative path, different content
            if size == 0:
                skipped += 1
                log.append("- skip empty differing: %s" % rel)
            elif rel.endswith(".db") or os.path.getmtime(p) > os.path.getmtime(canon_files[rel]):
                vdest = os.path.join(MERGED, slug, rel)
                os.makedirs(os.path.dirname(vdest), exist_ok=True)
                if not os.path.exists(vdest):
                    shutil.copy2(p, vdest)
                    copied_ver += 1
                    log.append("- VERSION kept: %s -> _merged_from/%s/%s (%d B)" % (rel, slug, rel, size))
            else:
                pass  # canonical is newer; old version preserved in Backups

# verification gate: every old file must be identical/dup in canonical, in _merged_from, or intentionally skipped
canon_hash2 = {sha(p) for p in files(CANON).values()}
for slug, tree in TREES.items():
    if not os.path.isdir(tree) or os.path.islink(tree):
        continue
    for rel, p in files(tree).items():
        if rel.endswith(TRANSIENT) or os.path.getsize(p) == 0:
            continue
        if sha(p) in canon_hash2:
            continue
        # canonical newer, non-db: acceptable only if canonical has same rel path
        if os.path.exists(os.path.join(CANON, rel)):
            continue
        unaccounted.append(p)

log.append("")
log.append("copied new: %d | versions kept: %d | skipped: %d | unaccounted: %d"
           % (copied_new, copied_ver, skipped, len(unaccounted)))
os.makedirs(MERGED, exist_ok=True)

if unaccounted:
    log.append("ABORT: nothing moved. Unaccounted: " + ", ".join(unaccounted[:20]))
    open(MERGED + "/MERGE_LOG_2026-10-04.md", "w").write("\n".join(log))
    print("\n".join(log))
    sys.exit(1)

os.makedirs(BACKUP, exist_ok=True)
for slug, tree in TREES.items():
    if os.path.isdir(tree) and not os.path.islink(tree):
        dest = os.path.join(BACKUP, slug)
        shutil.move(tree, dest)
        log.append("MOVED %s -> %s" % (tree.replace(H, "~/"), dest.replace(H, "~/")))
# keep old paths working: ~/NAA becomes a symlink to the canonical tree
link = H + "NAA"
if not os.path.exists(link) and not os.path.islink(link):
    os.symlink(CANON, link)
    log.append("SYMLINK ~/NAA -> %s" % CANON.replace(H, "~/"))

open(MERGED + "/MERGE_LOG_2026-10-04.md", "w").write("\n".join(log))
print("\n".join(log))
